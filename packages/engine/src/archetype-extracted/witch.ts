/**
 * Witch's slice of the pipeline, repeating the fighter pilot's methodology
 * (`./fighter.ts`) for the 42 vendored witch archetypes / 188 archetype
 * features. Per the per-class file convention (`./index.ts`'s doc comment),
 * this file owns BOTH of witch's pipeline artifacts —
 * `WITCH_ARCHETYPE_EFFECTS_EXTRACTED` (the machine-extracted `Change`-shaped
 * effects table) and `WITCH_ARCHETYPE_FEATURE_CLASSIFICATION` (the full
 * per-feature audit) — so a future wave working on a different class never
 * has a reason to touch this file; only `index.ts` (the aggregator) needs
 * one new import + one new spread per class.
 *
 * ── WITCH_ARCHETYPE_FEATURE_CLASSIFICATION ────────────────────────────────
 *
 * Every feature of every vendored witch archetype, read in full (188 is
 * small enough to read exhaustively rather than sample) and bucketed as
 * `numeric` / `situational` / `subsystem` / `blocked` per the same rubric
 * `fighter.ts` established:
 *  - "numeric": an unconditional bonus expressible via a real
 *    `packages/engine/src/targets.ts` target.
 *  - "situational": a REAL number scoped to a specific maneuver, weapon,
 *    location, relationship condition, or trigger the engine can't check
 *    without over-applying — vendored prose stays the source of truth.
 *  - "subsystem": grants an unrelated ability/resource/choice list, swaps
 *    the familiar/patron/spell-list for a differently-flavored version of
 *    the same subsystem, buffs a creature OTHER than the witch (an ally or
 *    an aura target), or otherwise has no Change-shaped number to extract.
 *  - "blocked": a genuine composition trap the engine structurally can't
 *    express without new machinery — recorded rather than guessed at.
 *
 * Witch is overwhelmingly hex/patron/familiar-flavored: the class's whole
 * identity is trading one flavor of hex/patron/familiar for another, or
 * bolting on an activated, resource-gated ability (swift/standard action,
 * uses/day) in the same vein as ki/grit/panache/Archaeologist's Luck
 * (`archetype-effects.ts`) — none of which is a flat always-on number. That
 * makes the `subsystem` bucket dominant here (172 of 188 features) and the
 * `numeric` bucket genuinely small (2) — honesty over volume, per this
 * pipeline's own rule (`docs/engine-cookbook.md` §3.4): a feature is only
 * promoted to `numeric` when the text is unconditional and lands on a real
 * target, never because a bucket "should" have more entries.
 *
 * One `blocked` entry: Seducer's Otherworldly Allure substitutes Charisma
 * for Intelligence across every witch class feature (bonus spells, max
 * spell level, spells known, every spell/hex save DC) — a real,
 * unconditional effect, but `ability-substitution.ts`'s registry only covers
 * a fixed set of derived slots (AC, initiative, attack/damage, CMB/CMD,
 * Reflex saves) and has no "casting ability" slot, while the witch's
 * spellcasting formulas hardcode Intelligence rather than reading through a
 * swappable slot. Composing this correctly needs a new substitution slot
 * (engine work), not a table entry.
 */

