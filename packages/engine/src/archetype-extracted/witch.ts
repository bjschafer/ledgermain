export const WITCH_ARCHETYPE_EFFECTS_EXTRACTED: Readonly<
  Record<string, ExtractedArchetypeFeatureEffect>
> = {
  // Hagbound's "Hunched Muscle" (Pathfinder Player Companion: Blood of the
  // Coven p. 16): "She gains a +2 size bonus to her Strength score. This
  // bonus increases by 2 at 8th level and 14th level, to a maximum of +6."
  // Unconditional, no gating clause — a flat, always-on ability-score bonus,
  // same target shape as the sorcerer bloodline power/eidolon evolution
  // ability-score bumps elsewhere in the engine (`c("...", "str", "size")`).
  "witch:hagbound:hunched-muscle:2": {
    changes: [
      c("2 + if(gte(@class.unlevel, 8), 2, 0) + if(gte(@class.unlevel, 14), 2, 0)", "str", "size"),
    ],
    detail: (level) => `+${level >= 14 ? 6 : level >= 8 ? 4 : 2} size bonus to Strength`,
    confidence: "high",
    provenance:
      "She gains a +2 size bonus to her Strength score. This bonus increases by 2 at 8th level and 14th level, to a maximum of +6.",
  },

  // Herb Witch's "Herb Lore" (Ultimate Wilderness p. 89): "she gains a bonus
  // on Profession (herbalist) checks equal to half her class level."
  // Unconditional, no stated minimum (unlike Cloistered Cleric's Breadth of
  // Knowledge). Targets a specific named Profession instance, same
  // "player must have created a matching-slug skill instance" shape as the
  // hand-verified table's Sorcerer of Sleep -> `skill.crf.alchemy` precedent
  // (`archetype-effects.ts`).
  "witch:herb-witch:herb-lore:0": {
    changes: [c("floor(@class.unlevel / 2)", "skill.pro.herbalist")],
    detail: (level) => `+${Math.floor(level / 2)} Profession (herbalist)`,
    confidence: "high",
    provenance: "she gains a bonus on Profession (herbalist) checks equal to half her class level.",
  },
};

